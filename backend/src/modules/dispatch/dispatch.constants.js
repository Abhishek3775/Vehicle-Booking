/**
 * Dispatch Module Constants
 *
 * Defines dispatch statuses, assignment types, lifecycle transition rules,
 * and search/retry boundaries.
 */

const DISPATCH_STATUS = Object.freeze({
  PENDING: 'PENDING',
  SEARCHING: 'SEARCHING',
  ASSIGNED: 'ASSIGNED',
  ACCEPTED: 'ACCEPTED',
  REJECTED: 'REJECTED',
  CANCELLED: 'CANCELLED',
  COMPLETED: 'COMPLETED',
  FAILED: 'FAILED',
});

const ASSIGNMENT_TYPES = Object.freeze({
  MANUAL: 'MANUAL',
  AUTO: 'AUTO',
});

// Active statuses where a dispatch process is considered live / ongoing
const ACTIVE_DISPATCH_STATUSES = Object.freeze([
  DISPATCH_STATUS.PENDING,
  DISPATCH_STATUS.SEARCHING,
  DISPATCH_STATUS.ASSIGNED,
  DISPATCH_STATUS.ACCEPTED,
]);

// Controlled lifecycle state transitions
const ALLOWED_TRANSITIONS = Object.freeze({
  [DISPATCH_STATUS.PENDING]: [
    DISPATCH_STATUS.SEARCHING,
    DISPATCH_STATUS.ASSIGNED,
    DISPATCH_STATUS.CANCELLED,
    DISPATCH_STATUS.FAILED,
  ],
  [DISPATCH_STATUS.SEARCHING]: [
    DISPATCH_STATUS.ASSIGNED,
    DISPATCH_STATUS.CANCELLED,
    DISPATCH_STATUS.FAILED,
  ],
  [DISPATCH_STATUS.ASSIGNED]: [
    DISPATCH_STATUS.ACCEPTED,
    DISPATCH_STATUS.REJECTED,
    DISPATCH_STATUS.CANCELLED,
    DISPATCH_STATUS.SEARCHING,
  ],
  [DISPATCH_STATUS.ACCEPTED]: [
    DISPATCH_STATUS.COMPLETED,
    DISPATCH_STATUS.CANCELLED,
  ],
  [DISPATCH_STATUS.REJECTED]: [
    DISPATCH_STATUS.SEARCHING,
    DISPATCH_STATUS.ASSIGNED,
    DISPATCH_STATUS.FAILED,
    DISPATCH_STATUS.CANCELLED,
  ],
  [DISPATCH_STATUS.FAILED]: [
    DISPATCH_STATUS.SEARCHING,
    DISPATCH_STATUS.ASSIGNED,
    DISPATCH_STATUS.CANCELLED,
  ],
  [DISPATCH_STATUS.CANCELLED]: [],
  [DISPATCH_STATUS.COMPLETED]: [],
});

